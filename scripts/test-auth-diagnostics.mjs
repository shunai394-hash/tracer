import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const base = await readFile(new URL("../app/api/channels/base/diagnostics/route.ts", import.meta.url), "utf8");
const shopify = await readFile(new URL("../app/api/admin/shopify/auth-check/route.ts", import.meta.url), "utf8");
const workflow = await readFile(new URL("../.github/workflows/tracer-shopify-auth-check.yml", import.meta.url), "utf8");
const baseClient = await readFile(new URL("../lib/channels/base.ts", import.meta.url), "utf8");

assert.match(base, /requireAutomationAuth/);
assert.match(base, /TRACER BASE AUTH PROBE/);
assert.match(base, /message\.match\(\/HTTP_.*\\d\{3\}.*\)/);
assert.match(base, /error: stage/);
assert.doesNotMatch(base, /error:\s*error instanceof Error\s*\?\s*error\.message/);
assert.doesNotMatch(base, /unique_key/);
assert.match(base, /probeBaseReadOnly/);
assert.match(base, /createSupabaseAdminClient/);
assert.match(base, /getPublishableSupplierListingStatuses/, "BASE audit must use the same publication-safe supplier identity predicate as the publisher");
assert.match(base, /supplier_product_id,supplier_variant_id/, "legacy listing audit must load the exact supplier tuple");
assert.match(base, /supplierStatuses\.has\(String\(legacyMatches\[0\]\.id\)\)/, "native verified CJ offers may pass without marketplace identity promotion");
assert.doesNotMatch(base, /getLinkedSupplierListingIds/, "audit must not treat supply_discovered as automatically unfulfillable");
assert.match(base, /visibleItemsUnlinked/);
assert.match(base, /visibleItemsWithoutDbMapping/);
assert.match(base, /visibleItemsWithAmbiguousDbMapping/);
assert.match(base, /commerceFulfillmentBlockReasons/, "BASE diagnostics must report specific fulfilment blockers");
assert.match(base, /commerceEvidenceStaleCount/, "BASE diagnostics must expose evidence age separately");
assert.match(base, /if \(offer && !fresh\) mappingAudit\.commerceEvidenceStaleCount \+= 1;/, "stale evidence is counted independently");
assert.doesNotMatch(base, /blockers\.push\("evidence_stale"\)/, "age alone must not be treated as a publication blocker");
assert.doesNotMatch(base, /entries: probe\.items\.entries|itemIds:/);
const responseBlock = base.slice(base.indexOf("const result ="), base.indexOf("console.info"));
assert.doesNotMatch(responseBlock, /item_id|unique_key|entries|itemIds/);
assert.match(baseClient, /BASE_ITEMS_PROBE_FAILED/);
assert.match(baseClient, /\/items\?limit=/);
assert.match(baseClient, /visibleCount/);
assert.match(baseClient, /unknownVisibilityCount/);
assert.match(baseClient, /itemMaxPages/);
// The production BASE shop has more than 1,000 items; read-only scans must be
// able to finish (cap 50 pages x 100) or the mapping audit never runs.
assert.match(baseClient, /export const BASE_ITEMS_MAX_PAGES = 50;/);
assert.match(baseClient, /options\?\.itemMaxPages \?\? BASE_ITEMS_MAX_PAGES/);
assert.equal((baseClient.match(/options\?\.itemMaxPages \?\? BASE_ITEMS_MAX_PAGES/g) ?? []).length, 2, "BASE diagnostics and snapshots default to the full 5,000-item scan");
assert.doesNotMatch(baseClient, /Math\.min\(10, Math\.max\(1, Math\.floor\(options\?\.itemMaxPages/);
assert.match(base, /probeBaseReadOnly\(\{ itemPageLimit: 100, itemMaxPages: BASE_ITEMS_MAX_PAGES \}\)/);
assert.match(base, /externalIds\.slice\(offset, offset \+ 100\)/, "BASE item-id audit must batch database lookups so a 5,000 item scan is not truncated");
const commerceStatus = await readFile(new URL("../app/api/admin/commerce/status/route.ts", import.meta.url), "utf8");
assert.match(commerceStatus, /readOnly: true/);
assert.match(commerceStatus, /livePlatforms: \{ base: baseLive, shopify: shopifyLive \}/);
assert.match(commerceStatus, /probeBaseReadOnly\(\{ itemPageLimit: 100, itemMaxPages: BASE_ITEMS_MAX_PAGES \}\)/);
assert.match(commerceStatus, /productsCount\(query: "status:active"/);
assert.match(commerceStatus, /Cache-Control": "no-store"/);
assert.match(shopify, /probeShopifyAuth/);
assert.match(shopify, /const scopeReady = adminApi\.ok === true[\s\S]*?adminApi\.missingScopes\.length === 0/);
assert.match(shopify, /ok: shopifyProbe\.ok && scopeReady/);
assert.match(shopify, /scopeReady,/);
assert.ok(workflow.includes("api/channels/base/diagnostics"), "read-only auth workflow must include BASE diagnostics");
assert.match(workflow, /baseIdentityRepair/);
assert.match(workflow, /outcomeCounts/);
assert.match(workflow, /sourceCounts/);
assert.match(workflow, /base-identity-repair\.json/);
assert.match(workflow, /readiness\.pop\("rows", \[\]\)/, "auth report must not embed the full row-level Shopify identity audit");
assert.match(workflow, /readiness\["rowsReturned"\] = len\(readiness_rows\)/, "auth report must preserve the number of audited rows after compacting");
assert.match(workflow, /len\(report_json\) > 48000/, "auth report must shrink samples before approaching the GitHub issue limit");
assert.match(workflow, /AUTH_REPORT_EXCEEDS_SAFE_ISSUE_BODY_LIMIT/, "auth report must fail with a clear guard instead of an opaque GitHub API error");
assert.doesNotMatch(workflow, /baseIdentityRepair[^\n]*(?:baseItemId|listingId)/, "identity report must include counts, not item IDs");
assert.match(workflow, /BASE_APPLY=false[\s\S]*?github\.event_name[^\n]*workflow_dispatch[\s\S]*?apply_exact_base_links/, "BASE identity repair must require an explicit manual opt-in");
assert.doesNotMatch(workflow, /github\.event_name[^\n]*push[^\n]*BASE_APPLY=true/, "push-triggered audits must never enable BASE writes");
assert.match(workflow, /Automatic triggers are read-only/, "diagnostic report must state the automatic trigger write policy");
