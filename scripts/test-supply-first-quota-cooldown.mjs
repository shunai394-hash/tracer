import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const source = await readFile(new URL("../app/api/cron/supply-first/route.ts", import.meta.url), "utf8");
const vercel = JSON.parse(await readFile(new URL("../vercel.json", import.meta.url), "utf8"));
const quotaCheck = source.indexOf('.eq("job_name", "cj-api-quota-circuit")');
const cachedLookup = source.indexOf('.from("supplier_listings")');
const runInsert = source.indexOf('.from("cron_runs").insert({');
const discoveryCall = source.indexOf("await discoverAndCreateCjSupply(");
assert.ok(quotaCheck >= 0, "supply-first must read the persisted CJ quota circuit");
assert.ok(cachedLookup > quotaCheck && cachedLookup < runInsert, "cached eligibility must be checked before creating a run record");
assert.ok(runInsert > cachedLookup, "eligible cached supply proceeds into a recorded run");
assert.ok(discoveryCall > runInsert, "discovery remains available only after the cached-only cooldown branch");
const cooldownBranch = source.slice(cachedLookup, runInsert);
assert.match(cooldownBranch, /price_confirmed", true/, "cached offers require confirmed price");
assert.match(cooldownBranch, /inventory_confirmed", true/, "cached offers require confirmed stock");
assert.match(cooldownBranch, /orderable", true/, "cached offers require explicit supplier orderability");
assert.match(cooldownBranch, /tracking_available", true/, "cached offers require tracking capability");
assert.match(cooldownBranch, /api_available", true/, "cached offers require supplier API availability");
assert.match(cooldownBranch, /supplier_quota_cooldown_no_verified_cached_supply/, "empty cooldown cache must return a clear no-op reason");
assert.match(cooldownBranch, /runRecordCreated: false/, "empty cooldown cache must not create noisy run records");
assert.match(cooldownBranch, /retryAfter: blockedUntil/, "cooldown response must preserve the retry time");
assert.match(source, /selectAndPublishSupplySalesTests\(verifiedProductIds/, "cached verified products must continue through the normal publication gate");
const supplyCron = vercel.crons.find((cron) => cron.path === "/api/cron/supply-first");
const identityCron = vercel.crons.find((cron) => cron.path === "/api/cron/cj-identity-reverify");
assert.equal(supplyCron?.schedule, "2,32 * * * *", "supply-first must be staggered away from identity re-verification");
assert.equal(identityCron?.schedule, "12,27,42,57 * * * *", "identity re-verification schedule remains explicit");
console.log("Supply-first CJ quota cooldown and schedule: 13 invariants passed");
