import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const source = await readFile(new URL("../app/api/cron/supply-first/route.ts", import.meta.url), "utf8");
const quotaCheck = source.indexOf('.eq("job_name", "cj-api-quota-circuit")');
const runInsert = source.indexOf('.from("cron_runs").insert({');
const cachedLookup = source.indexOf('.from("supplier_listings")');
const discoveryCall = source.indexOf("await discoverAndCreateCjSupply(");
assert.ok(quotaCheck >= 0, "supply-first must read the persisted CJ quota circuit");
assert.ok(runInsert > quotaCheck, "quota state must be known before the run is recorded");
assert.ok(cachedLookup > runInsert, "cooldown path must re-check persisted supplier offers after run start");
assert.ok(discoveryCall > cachedLookup, "discovery remains available after the cached-only cooldown branch");
const cooldownBranch = source.slice(cachedLookup, discoveryCall);
assert.match(cooldownBranch, /price_confirmed", true/, "cached offers require confirmed price");
assert.match(cooldownBranch, /inventory_confirmed", true/, "cached offers require confirmed stock");
assert.match(cooldownBranch, /orderable", true/, "cached offers require explicit supplier orderability");
assert.match(cooldownBranch, /tracking_available", true/, "cached offers require tracking capability");
assert.match(cooldownBranch, /api_available", true/, "cached offers require supplier API availability");
assert.match(cooldownBranch, /cj_quota_cooldown_using_cached_orderable_supply/, "cooldown runs must report cached-supply behavior");
assert.match(cooldownBranch, /retryAfter: blockedUntil/, "cooldown response metadata must preserve the retry time");
assert.match(source, /selectAndPublishSupplySalesTests\(verifiedProductIds/, "cached verified products must continue through the normal publication gate");
console.log("Supply-first CJ quota cooldown: 10 invariants passed");
